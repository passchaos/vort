#!/usr/bin/env python3
"""Create a test-only liblzma 5.8.4 MT decoder instrumentation source tree.

The original tree is read-only. This tool copies it to a new output directory,
patches actual Block decoder calls, and records source and patch identities.
It does not run a compiler, decoder, timer, Git command, or network request.

Build the generated tree separately with threading and shared libraries enabled.
The generated ABI header documents a process-global probe: the harness must
serialize operations, reset before initialization, call lzma_end() to join all
workers, and only then snapshot. Counters are evidence of execution, not a
performance measurement. There are no sleeps, barriers, or artificial delays.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import difflib
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys

sys.dont_write_bytecode = True

COUNTERS = (
    "workers_created", "worker_threads_entered", "worker_threads_exited",
    "worker_threads_live", "worker_jobs_entered", "worker_jobs_completed",
    "worker_jobs_failed", "worker_jobs_abandoned", "worker_decode_calls",
    "worker_call_input_bytes", "worker_call_output_bytes",
    "active_worker_decode_calls", "peak_active_worker_decode_calls",
    "active_worker_jobs", "peak_active_worker_jobs", "worker_call_identity_mask",
    "worker_completed_identity_mask", "worker_call_distinct",
    "worker_completed_distinct", "worker_identity_overflow",
    "direct_blocks_initialized", "direct_blocks_completed", "direct_decode_calls",
    "direct_call_input_bytes", "direct_call_output_bytes",
    "direct_reason_missing_size", "direct_reason_oversized",
    "direct_reason_memory_limit", "direct_reason_memory_overflow",
    "invariant_failures",
)
DECODER = "src/liblzma/common/stream_decoder_mt.c"
HEADER = "src/liblzma/common/vort_xz_mt_probe.h"
MAPS = ("src/liblzma/liblzma_linux.map", "src/liblzma/liblzma_generic.map")
EXPORTS = ("vort_xz_mt_probe_abi_version", "vort_xz_mt_probe_reset",
           "vort_xz_mt_probe_snapshot")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def header() -> str:
    fields = "\n".join(f"\tVORT_MT_{name.upper()} = {i},"
                       for i, name in enumerate(COUNTERS))
    return """/* Test-only ABI generated by tools/xz/block_sizes_mt_patch.py. */
#ifndef VORT_XZ_MT_PROBE_H
#define VORT_XZ_MT_PROBE_H
#include <stdint.h>
#include <stddef.h>
#if defined(_WIN32)
# define VORT_MT_EXPORT __declspec(dllexport)
#elif defined(__GNUC__) || defined(__clang__)
# define VORT_MT_EXPORT __attribute__((visibility("default")))
#else
# define VORT_MT_EXPORT
#endif
#ifdef __cplusplus
extern "C" {
#endif
enum vort_xz_mt_probe_counter {
""" + fields + f"\n\tVORT_MT_COUNTER_COUNT = {len(COUNTERS)}\n" + """};
/* Process-global probe. Serialize all profiled decoder operations. Reset only
 * before decoder initialization and after the preceding lzma_end(). Snapshot
 * only after lzma_end(), which joins workers and finalizes abandoned jobs.
 * reset() returns -1 while workers/jobs/calls remain active; concurrent reset
 * and decoder initialization are unsupported even though counters are atomic.
 * snapshot() returns -1 for a null pointer or a count other than COUNTER_COUNT.
 * Successful reset and snapshot return zero. ABI version is 1.
 *
 * Worker identity tokens are allocated at the actual worker_decoder entry,
 * not when threads are configured or jobs queued. Bitmaps cover tokens 1..64;
 * worker_identity_overflow records tokens beyond that bound. Call and complete
 * bitmaps include only identities that actually called the Block decoder or
 * completed a Block, respectively. Use <=64 threads and require overflow=0.
 * peak_active_worker_decode_calls brackets real block_decoder.code() calls.
 * peak_active_worker_jobs spans each job from its first real call to completion
 * or abandonment, including input waits; it is not proof of simultaneous calls.
 * No timestamp, delay, barrier or performance metric is recorded.
 */
VORT_MT_EXPORT uint32_t vort_xz_mt_probe_abi_version(void);
VORT_MT_EXPORT int vort_xz_mt_probe_reset(void);
VORT_MT_EXPORT int vort_xz_mt_probe_snapshot(uint64_t *values, size_t count);
#ifdef __cplusplus
}
#endif
#endif
"""


INSTRUMENTATION = r'''
/* Test-only execution evidence. Counter updates never affect decoder results.
 * C11 atomics protect the one process-global profile across reference workers.
 * The serialized harness resets before init and snapshots after lzma_end(). */
#include <stdatomic.h>
#include "vort_xz_mt_probe.h"

static _Atomic uint64_t vort_mt_counters[VORT_MT_COUNTER_COUNT];

static void
vort_mt_add(enum vort_xz_mt_probe_counter key, uint64_t amount)
{
	atomic_fetch_add_explicit(&vort_mt_counters[key], amount, memory_order_relaxed);
}

static void
vort_mt_peak(enum vort_xz_mt_probe_counter key, uint64_t value)
{
	uint64_t old = atomic_load_explicit(&vort_mt_counters[key], memory_order_relaxed);
	while (old < value && !atomic_compare_exchange_weak_explicit(
			&vort_mt_counters[key], &old, value,
			memory_order_relaxed, memory_order_relaxed)) {}
}

static void
vort_mt_decrement(enum vort_xz_mt_probe_counter key)
{
	const uint64_t old = atomic_fetch_sub_explicit(
			&vort_mt_counters[key], 1, memory_order_seq_cst);
	if (old == 0)
		vort_mt_add(VORT_MT_INVARIANT_FAILURES, 1);
}

static void
vort_mt_identity(enum vort_xz_mt_probe_counter key, uint64_t identity)
{
	if (identity >= 1 && identity <= 64)
		atomic_fetch_or_explicit(&vort_mt_counters[key],
				UINT64_C(1) << (identity - 1), memory_order_relaxed);
}

static uint64_t
vort_mt_thread_enter(void)
{
	const uint64_t identity = atomic_fetch_add_explicit(
			&vort_mt_counters[VORT_MT_WORKER_THREADS_ENTERED],
			1, memory_order_relaxed) + 1;
	vort_mt_add(VORT_MT_WORKER_THREADS_LIVE, 1);
	if (identity > 64)
		vort_mt_add(VORT_MT_WORKER_IDENTITY_OVERFLOW, 1);
	return identity;
}

static void
vort_mt_job_enter(void)
{
	vort_mt_add(VORT_MT_WORKER_JOBS_ENTERED, 1);
	const uint64_t active = atomic_fetch_add_explicit(
			&vort_mt_counters[VORT_MT_ACTIVE_WORKER_JOBS],
			1, memory_order_seq_cst) + 1;
	vort_mt_peak(VORT_MT_PEAK_ACTIVE_WORKER_JOBS, active);
}

static void
vort_mt_job_exit(uint64_t identity, enum vort_xz_mt_probe_counter outcome)
{
	vort_mt_add(outcome, 1);
	if (outcome == VORT_MT_WORKER_JOBS_COMPLETED)
		vort_mt_identity(VORT_MT_WORKER_COMPLETED_IDENTITY_MASK, identity);
	vort_mt_decrement(VORT_MT_ACTIVE_WORKER_JOBS);
}

static void
vort_mt_call_enter(uint64_t identity)
{
	vort_mt_identity(VORT_MT_WORKER_CALL_IDENTITY_MASK, identity);
	vort_mt_add(VORT_MT_WORKER_DECODE_CALLS, 1);
	const uint64_t active = atomic_fetch_add_explicit(
			&vort_mt_counters[VORT_MT_ACTIVE_WORKER_DECODE_CALLS],
			1, memory_order_seq_cst) + 1;
	vort_mt_peak(VORT_MT_PEAK_ACTIVE_WORKER_DECODE_CALLS, active);
}

static void
vort_mt_progress(enum vort_xz_mt_probe_counter in_key,
		enum vort_xz_mt_probe_counter out_key, size_t in_old,
		size_t in_new, size_t out_old, size_t out_new)
{
	if (in_new < in_old || out_new < out_old) {
		vort_mt_add(VORT_MT_INVARIANT_FAILURES, 1);
		return;
	}
	vort_mt_add(in_key, in_new - in_old);
	vort_mt_add(out_key, out_new - out_old);
}

static uint64_t
vort_mt_bit_count(uint64_t value)
{
	uint64_t result = 0;
	while (value != 0) {
		value &= value - 1;
		++result;
	}
	return result;
}

VORT_MT_EXPORT uint32_t
vort_xz_mt_probe_abi_version(void)
{
	return 1;
}

VORT_MT_EXPORT int
vort_xz_mt_probe_reset(void)
{
	if (atomic_load_explicit(&vort_mt_counters[VORT_MT_WORKER_THREADS_LIVE],
			memory_order_acquire) != 0
			|| atomic_load_explicit(&vort_mt_counters[VORT_MT_ACTIVE_WORKER_JOBS],
				memory_order_acquire) != 0
			|| atomic_load_explicit(&vort_mt_counters[VORT_MT_ACTIVE_WORKER_DECODE_CALLS],
				memory_order_acquire) != 0)
		return -1;
	for (size_t i = 0; i < VORT_MT_COUNTER_COUNT; ++i)
		atomic_store_explicit(&vort_mt_counters[i], 0, memory_order_relaxed);
	return 0;
}

VORT_MT_EXPORT int
vort_xz_mt_probe_snapshot(uint64_t *values, size_t count)
{
	if (values == NULL || count != VORT_MT_COUNTER_COUNT)
		return -1;
	for (size_t i = 0; i < VORT_MT_COUNTER_COUNT; ++i)
		values[i] = atomic_load_explicit(&vort_mt_counters[i], memory_order_acquire);
	values[VORT_MT_WORKER_CALL_DISTINCT]
			= vort_mt_bit_count(values[VORT_MT_WORKER_CALL_IDENTITY_MASK]);
	values[VORT_MT_WORKER_COMPLETED_DISTINCT]
			= vort_mt_bit_count(values[VORT_MT_WORKER_COMPLETED_IDENTITY_MASK]);
	return 0;
}
'''


def replace_once(text: str, before: str, after: str, label: str) -> str:
    count = text.count(before)
    if count != 1:
        raise ValueError(f"{label}: expected one unchanged 5.8.4 anchor, found {count}")
    return text.replace(before, after, 1)


def patch_decoder(original: str) -> str:
    if "vort_xz_mt_probe" in original:
        raise ValueError("source decoder is already instrumented")
    text = replace_once(original, '#include "outqueue.h"\n',
                        '#include "outqueue.h"\n' + INSTRUMENTATION, "probe definitions")
    text = replace_once(text, "\tsize_t in_filled;\n\tbool partial_update_enabled;\n\tlzma_ret ret;",
                        "\tsize_t in_filled;\n\tbool partial_update_enabled;\n\tlzma_ret ret;\n"
                        "\tconst uint64_t vort_worker_identity = vort_mt_thread_enter();\n"
                        "\tbool vort_job_active = false;", "actual worker entry")
    text = replace_once(text, "\tif (thr->state == THR_IDLE) {\n\t\tmythread_cond_wait",
                        "\tif (thr->state == THR_IDLE) {\n"
                        "\t\tif (vort_job_active) {\n"
                        "\t\t\tvort_mt_job_exit(vort_worker_identity, VORT_MT_WORKER_JOBS_ABANDONED);\n"
                        "\t\t\tvort_job_active = false;\n\t\t}\n\t\tmythread_cond_wait",
                        "abandoned job on stop")
    text = replace_once(text, "\tif (thr->state == THR_EXIT) {\n\t\tmythread_mutex_unlock",
                        "\tif (thr->state == THR_EXIT) {\n"
                        "\t\tif (vort_job_active) {\n"
                        "\t\t\tvort_mt_job_exit(vort_worker_identity, VORT_MT_WORKER_JOBS_ABANDONED);\n"
                        "\t\t\tvort_job_active = false;\n\t\t}\n\t\tmythread_mutex_unlock",
                        "abandoned job on exit")
    text = replace_once(text, "\t\treturn MYTHREAD_RET_VALUE;\n\t}\n\n\tassert(thr->state == THR_RUN);",
                        "\t\tvort_mt_add(VORT_MT_WORKER_THREADS_EXITED, 1);\n"
                        "\t\tvort_mt_decrement(VORT_MT_WORKER_THREADS_LIVE);\n"
                        "\t\treturn MYTHREAD_RET_VALUE;\n\t}\n\n\tassert(thr->state == THR_RUN);",
                        "actual worker exit")
    text = replace_once(text, "\tret = thr->block_decoder.code(\n",
                        "\tif (!vort_job_active) {\n\t\tvort_mt_job_enter();\n"
                        "\t\tvort_job_active = true;\n\t}\n"
                        "\tconst size_t vort_in_old = thr->in_pos;\n"
                        "\tconst size_t vort_out_old = thr->out_pos;\n"
                        "\tvort_mt_call_enter(vort_worker_identity);\n"
                        "\tret = thr->block_decoder.code(\n", "actual Block decoder call entry")
    text = replace_once(text, "\t\t\tthr->outbuf->allocated, LZMA_RUN);\n\n\tif (ret == LZMA_OK)",
                        "\t\t\tthr->outbuf->allocated, LZMA_RUN);\n"
                        "\tvort_mt_decrement(VORT_MT_ACTIVE_WORKER_DECODE_CALLS);\n"
                        "\tvort_mt_progress(VORT_MT_WORKER_CALL_INPUT_BYTES, VORT_MT_WORKER_CALL_OUTPUT_BYTES,\n"
                        "\t\t\tvort_in_old, thr->in_pos, vort_out_old, thr->out_pos);\n\n"
                        "\tif (ret == LZMA_OK)", "actual Block decoder call exit")
    text = replace_once(text, "\t// Free the input buffer. Don't update in_size as we need\n",
                        "\tif (!vort_job_active)\n\t\tvort_mt_add(VORT_MT_INVARIANT_FAILURES, 1);\n"
                        "\telse {\n\t\tvort_mt_job_exit(vort_worker_identity, ret == LZMA_STREAM_END\n"
                        "\t\t\t\t? VORT_MT_WORKER_JOBS_COMPLETED : VORT_MT_WORKER_JOBS_FAILED);\n"
                        "\t\tvort_job_active = false;\n\t}\n\n"
                        "\t// Free the input buffer. Don't update in_size as we need\n",
                        "final Block completion or failure")
    text = replace_once(text, "\t++coder->threads_initialized;\n\tcoder->thr = thr;",
                        "\tvort_mt_add(VORT_MT_WORKERS_CREATED, 1);\n"
                        "\t++coder->threads_initialized;\n\tcoder->thr = thr;",
                        "successful native thread creation")
    text = replace_once(text, "\t\t\tcoder->block_options.uncompressed_size)) {\n"
                        "\t\t\tcoder->sequence = SEQ_BLOCK_DIRECT_INIT;",
                        "\t\t\tcoder->block_options.uncompressed_size)) {\n"
                        "\t\t\tif (coder->block_options.compressed_size == LZMA_VLI_UNKNOWN\n"
                        "\t\t\t\t\t|| coder->block_options.uncompressed_size == LZMA_VLI_UNKNOWN)\n"
                        "\t\t\t\tvort_mt_add(VORT_MT_DIRECT_REASON_MISSING_SIZE, 1);\n"
                        "\t\t\tif ((coder->block_options.compressed_size != LZMA_VLI_UNKNOWN\n"
                        "\t\t\t\t\t&& coder->block_options.compressed_size > SIZE_MAX / 3)\n"
                        "\t\t\t\t\t|| (coder->block_options.uncompressed_size != LZMA_VLI_UNKNOWN\n"
                        "\t\t\t\t\t&& coder->block_options.uncompressed_size > SIZE_MAX / 3))\n"
                        "\t\t\t\tvort_mt_add(VORT_MT_DIRECT_REASON_OVERSIZED, 1);\n"
                        "\t\t\tcoder->sequence = SEQ_BLOCK_DIRECT_INIT;", "direct size reasons")
    text = replace_once(text, "\t\tif (UINT64_MAX - mem_buffers < coder->mem_next_filters) {\n",
                        "\t\tif (UINT64_MAX - mem_buffers < coder->mem_next_filters) {\n"
                        "\t\t\tvort_mt_add(VORT_MT_DIRECT_REASON_MEMORY_OVERFLOW, 1);\n",
                        "direct memory overflow")
    text = replace_once(text, "\t\tif (coder->mem_next_block > coder->memlimit_threading) {\n",
                        "\t\tif (coder->mem_next_block > coder->memlimit_threading) {\n"
                        "\t\t\tvort_mt_add(VORT_MT_DIRECT_REASON_MEMORY_LIMIT, 1);\n",
                        "direct threading memory limit")
    text = replace_once(text, "\t\tcoder->sequence = SEQ_BLOCK_DIRECT_RUN;\n",
                        "\t\tvort_mt_add(VORT_MT_DIRECT_BLOCKS_INITIALIZED, 1);\n"
                        "\t\tcoder->sequence = SEQ_BLOCK_DIRECT_RUN;\n", "direct successful init")
    text = replace_once(text, "\t\tconst lzma_ret ret = coder->block_decoder.code(\n",
                        "\t\tvort_mt_add(VORT_MT_DIRECT_DECODE_CALLS, 1);\n"
                        "\t\tconst lzma_ret ret = coder->block_decoder.code(\n", "direct real call")
    text = replace_once(text, "\t\t\t\taction);\n\t\tcoder->progress_in += *in_pos - in_old;",
                        "\t\t\t\taction);\n"
                        "\t\tvort_mt_progress(VORT_MT_DIRECT_CALL_INPUT_BYTES, VORT_MT_DIRECT_CALL_OUTPUT_BYTES,\n"
                        "\t\t\t\tin_old, *in_pos, out_old, *out_pos);\n"
                        "\t\tcoder->progress_in += *in_pos - in_old;", "direct call progress")
    text = replace_once(text, "\t\t// Block decoded successfully. Add the new size pair to\n",
                        "\t\tvort_mt_add(VORT_MT_DIRECT_BLOCKS_COMPLETED, 1);\n\n"
                        "\t\t// Block decoded successfully. Add the new size pair to\n",
                        "direct actual Block completion")
    return text


def tree_manifest(source: Path) -> tuple[str, list[dict]]:
    files = []
    for path in sorted(source.rglob("*")):
        relative = path.relative_to(source)
        if ".git" in relative.parts:
            continue
        if path.is_symlink():
            raise ValueError(f"source tree contains a symlink: {relative}")
        if path.is_file():
            data = path.read_bytes()
            files.append({"path": relative.as_posix(), "bytes": len(data), "sha256": sha256(data)})
    identity = "".join(f"{item['path']}\0{item['sha256']}\n" for item in files).encode()
    return sha256(identity), files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-tree", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, required=True,
                        help="New directory for patched xz/ and artifacts/; must not exist")
    args = parser.parse_args()
    source = args.source_tree.resolve()
    output = args.output_root.resolve()
    if not source.is_dir() or not (source / DECODER).is_file():
        raise ValueError("source-tree must be an unpacked XZ source tree")
    if output.exists() or output == source or source in output.parents or output in source.parents:
        raise ValueError("output-root must be new and outside the original source tree")
    version = (source / "src/liblzma/api/lzma/version.h").read_text()
    for key, value in (("MAJOR", 5), ("MINOR", 8), ("PATCH", 4)):
        if not re.search(rf"^#define LZMA_VERSION_{key}\s+{value}\s*$", version, re.MULTILINE):
            raise ValueError("instrumentation anchors are restricted to liblzma 5.8.4")

    replacements = {DECODER: patch_decoder((source / DECODER).read_text()), HEADER: header()}
    export_lines = "".join(f"\t{name};\n" for name in EXPORTS)
    for name in MAPS:
        text = (source / name).read_text()
        if text.count("XZ_5.0 {\nglobal:\n") != 1:
            raise ValueError(f"{name}: missing original export-map anchor")
        replacements[name] = text.replace("XZ_5.0 {\nglobal:\n",
                                          "XZ_5.0 {\nglobal:\n" + export_lines, 1)

    original_tree_sha, original_files = tree_manifest(source)
    patched_tree = output / "xz"
    artifacts = output / "artifacts"
    output.mkdir(parents=True)
    shutil.copytree(source, patched_tree, ignore=shutil.ignore_patterns(".git"))
    artifacts.mkdir()
    edits = []
    patch_parts = []
    for name, text in replacements.items():
        original = (source / name).read_bytes() if (source / name).exists() else b""
        target = patched_tree / name
        target.write_text(text)
        after = target.read_bytes()
        edits.append({"path": name, "original_sha256": sha256(original) if original else None,
                      "patched_sha256": sha256(after), "original_bytes": len(original),
                      "patched_bytes": len(after)})
        patch_parts.extend(difflib.unified_diff(original.decode().splitlines(keepends=True),
                                              text.splitlines(keepends=True),
                                              fromfile=f"a/{name}" if original else "/dev/null",
                                              tofile=f"b/{name}"))
    patch_path = artifacts / "liblzma-5.8.4-mt-probe.patch"
    patch_path.write_text("".join(patch_parts))
    header_path = artifacts / "vort_xz_mt_probe.h"
    header_path.write_text(header())
    patched_tree_sha, _ = tree_manifest(patched_tree)
    original_index_path = artifacts / "original-source-files.json"
    original_index_path.write_text(json.dumps(original_files, indent=2) + "\n")
    manifest = {
        "schema": "vort-xz-mt-probe-source-v1", "abi_version": 1,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "reference_version": "5.8.4", "original_source_tree": str(source),
        "original_tree_sha256": original_tree_sha, "patched_source_tree": str(patched_tree),
        "patched_tree_sha256": patched_tree_sha,
        "original_source_index": str(original_index_path),
        "patch": {"path": str(patch_path), "sha256": sha256(patch_path.read_bytes())},
        "script": {"path": str(Path(__file__).resolve()),
                   "sha256": sha256(Path(__file__).read_bytes())},
        "header": {"path": str(header_path), "sha256": sha256(header_path.read_bytes())},
        "changed_files": edits, "counters": dict(enumerate(COUNTERS)),
        "counter_count": len(COUNTERS), "exports": list(EXPORTS),
        "execution": {"compiler_launched": False, "decoder_launched": False,
                      "timing_measured": False, "artificial_delay_or_barrier": False},
        "build_record_required": ["compiler path/version", "configure command/options",
                                  "build command", "instrumented library path/SHA256",
                                  "reference wrapper source/compiler/executable SHA256"],
        "harness_contract": ["serialize all profiled decoder operations",
                             "reset before initializing the decoder",
                             "call lzma_end before snapshot or the next reset",
                             "use <=64 actual reference worker lifetimes per operation",
                             "require invariant_failures=0 and worker_identity_overflow=0",
                             "require active worker/jobs/calls=0 after lzma_end"],
        "evidence": {
            "actual_multiple_workers": "worker_completed_distinct > 1 with successful full decode",
            "natural_call_overlap": "peak_active_worker_decode_calls > 1 (observe; do not force)",
            "not_parallel_proof": ["workers_created", "worker_threads_entered",
                                   "peak_active_worker_jobs", "configured thread count"],
            "controls": ["unsized multiblock: missing-size direct blocks, zero worker calls",
                         "sized single block: one completed identity",
                         "sized multiblock with low threading memory: memory-limit direct blocks"],
        },
    }
    manifest_path = artifacts / "instrumentation.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"patched_source_tree": str(patched_tree), "manifest": str(manifest_path),
                      "patch": str(patch_path), "abi_header": str(header_path),
                      "counter_count": len(COUNTERS)}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print(f"block_sizes_mt_patch: {error}", file=sys.stderr)
        raise SystemExit(1)
