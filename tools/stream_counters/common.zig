const std = @import("std");

pub const Count = u64;
pub const chunk_len = 65536;
pub const pattern = makePattern();
fn makePattern() [chunk_len]u8 {
    @setEvalBranchQuota(2_000_000);
    var result: [chunk_len]u8 = undefined;
    var state: u32 = 0x51a7c0de;
    for (&result) |*byte| {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        byte.* = @truncate(state);
    }
    return result;
}

pub fn fill(bytes: []u8, offset: Count) void {
    var phase: usize = @intCast(offset % pattern.len);
    var position: usize = 0;
    while (position < bytes.len) {
        const take = @min(bytes.len - position, pattern.len - phase);
        @memcpy(bytes[position..][0..take], pattern[phase..][0..take]);
        position += take;
        phase = 0;
    }
}
pub fn verify(bytes: []const u8, offset: Count, rle: bool) !void {
    if (rle) {
        for (bytes) |byte| if (byte != 'R') return error.OutputContentMismatch;
    } else {
        var phase: usize = @intCast(offset % pattern.len);
        var position: usize = 0;
        while (position < bytes.len) {
            const take = @min(bytes.len - position, pattern.len - phase);
            if (!std.mem.eql(u8, bytes[position..][0..take], pattern[phase..][0..take])) return error.OutputContentMismatch;
            position += take;
            phase = 0;
        }
    }
}

/// Compact generated byte streams. Header bytes are materialized; payload
/// bytes are repeatedly regenerated into one bounded caller-owned buffer.
pub const Source = struct {
    family: enum { br_metadata, br_stored, zstd_skip },
    payload_bytes: Count,
    block_len: usize,
    remaining: Count,
    payload_emitted: Count = 0,
    header_bytes: [8]u8 = undefined,
    header_len: usize = 0,
    header_offset: usize = 0,
    body_remaining: usize = 0,
    first: bool = true,
    ended: bool = false,
    terminal: bool = false,
    buffer: [chunk_len]u8 = undefined,
    offered_body: bool = false,
    emitted_input: Count = 0,
    blocks: Count = 0,
    suffix: ?[]const u8 = null,
    suffix_offset: usize = 0,
    offered_suffix: bool = false,

    pub fn init(family: @FieldType(Source, "family"), payload_bytes: Count, block_len: usize) !Source {
        if (block_len == 0 or (family != .zstd_skip and block_len > 1 << 24)) return error.InvalidFixture;
        return .{ .family = family, .payload_bytes = payload_bytes, .block_len = block_len, .remaining = payload_bytes };
    }
    fn bits(self: *Source, bit: *usize, value: u64, count: usize) void {
        for (0..count) |i| {
            const item: u8 = @intCast((value >> @intCast(i)) & 1);
            self.header_bytes[bit.* / 8] |= item << @intCast(bit.* % 8);
            bit.* += 1;
        }
    }
    fn nextHeader(self: *Source) !void {
        @memset(&self.header_bytes, 0);
        self.header_offset = 0;
        if (self.remaining == 0) {
            if (self.family == .zstd_skip) {
                self.ended = true;
                return;
            }
            self.header_bytes[0] = if (self.first) 6 else 3;
            self.header_len = 1;
            self.terminal = true;
            return;
        }
        const size: usize = @intCast(@min(self.remaining, self.block_len));
        if (self.family == .zstd_skip) {
            self.header_bytes[0..4].* = .{ 0x50, 0x2a, 0x4d, 0x18 };
            std.mem.writeInt(u32, self.header_bytes[4..8], @intCast(size), .little);
            self.header_len = 8;
        } else {
            var bit: usize = 0;
            if (self.first) self.bits(&bit, 0, 1); // RFC window 16.
            self.bits(&bit, 0, 1); // Non-final block; independent final marker.
            if (self.family == .br_metadata) {
                self.bits(&bit, 3, 2);
                self.bits(&bit, 0, 1);
                const width: usize = if (size <= 256) 1 else if (size <= 65536) 2 else 3;
                self.bits(&bit, width, 2);
                self.bits(&bit, size - 1, width * 8);
            } else {
                const width: usize = if (size <= 65536) 16 else if (size <= 1048576) 20 else 24;
                self.bits(&bit, width / 4 - 4, 2);
                self.bits(&bit, size - 1, width);
                self.bits(&bit, 1, 1);
            }
            self.header_len = (bit + 7) / 8;
        }
        self.first = false;
        self.blocks += 1;
        self.body_remaining = size;
        self.remaining -= size;
    }
    pub fn next(self: *Source) ![]const u8 {
        self.offered_suffix = false;
        if (self.ended) return &.{};
        if (self.header_offset < self.header_len) {
            self.offered_body = false;
            return self.header_bytes[self.header_offset..self.header_len];
        }
        if (self.body_remaining != 0) {
            self.offered_body = true;
            const take = @min(self.body_remaining, self.buffer.len);
            fill(self.buffer[0..take], self.payload_emitted);
            return self.buffer[0..take];
        }
        if (self.terminal) {
            self.ended = true;
            return &.{};
        }
        if (self.remaining == 0 and self.suffix != null) {
            if (self.suffix_offset == self.suffix.?.len) {
                self.ended = true;
                return &.{};
            }
            self.offered_suffix = true;
            return self.suffix.?[self.suffix_offset..];
        }
        try self.nextHeader();
        return self.next();
    }
    pub fn consume(self: *Source, count: usize) void {
        self.emitted_input += count;
        if (self.offered_suffix) {
            self.suffix_offset += count;
        } else if (self.offered_body) {
            self.body_remaining -= count;
            self.payload_emitted += count;
        } else self.header_offset += count;
    }
};

pub const Progress = struct {
    input_read: Count = 0,
    output_written: Count = 0,
    steps: Count = 0,
    completed: bool = false,
};
pub fn consumeDecoder(decoder: anytype, offered: []const u8, output: []u8, progress: *Progress, rle: bool) !usize {
    const result = try decoder.step(offered, output);
    try verify(output[0..result.progress.output_written], progress.output_written, rle);
    progress.input_read += result.progress.input_read;
    progress.output_written += result.progress.output_written;
    progress.steps += 1;
    progress.completed = result.status == .done;
    if (result.progress.input_read == 0 and result.progress.output_written == 0 and result.status != .done and offered.len != 0)
        return error.NoProgress;
    return result.progress.input_read;
}

pub const Ledger = struct {
    backing: std.mem.Allocator,
    live: usize = 0,
    peak: usize = 0,
    allocations: Count = 0,
    pub fn allocator(self: *Ledger) std.mem.Allocator {
        return .{ .ptr = self, .vtable = &.{ .alloc = alloc, .resize = resize, .remap = remap, .free = free } };
    }
    fn changed(self: *Ledger, old: usize, new: usize) void {
        self.live = self.live - old + new;
        self.peak = @max(self.peak, self.live);
    }
    fn alloc(raw: *anyopaque, len: usize, alignment: std.mem.Alignment, ret: usize) ?[*]u8 {
        const self: *Ledger = @ptrCast(@alignCast(raw));
        const bytes = self.backing.rawAlloc(len, alignment, ret) orelse return null;
        self.changed(0, len);
        self.allocations += 1;
        return bytes;
    }
    fn resize(raw: *anyopaque, bytes: []u8, alignment: std.mem.Alignment, len: usize, ret: usize) bool {
        const self: *Ledger = @ptrCast(@alignCast(raw));
        if (!self.backing.rawResize(bytes, alignment, len, ret)) return false;
        self.changed(bytes.len, len);
        return true;
    }
    fn remap(raw: *anyopaque, bytes: []u8, alignment: std.mem.Alignment, len: usize, ret: usize) ?[*]u8 {
        const self: *Ledger = @ptrCast(@alignCast(raw));
        const moved = self.backing.rawRemap(bytes, alignment, len, ret) orelse return null;
        self.changed(bytes.len, len);
        return moved;
    }
    fn free(raw: *anyopaque, bytes: []u8, alignment: std.mem.Alignment, ret: usize) void {
        const self: *Ledger = @ptrCast(@alignCast(raw));
        self.backing.rawFree(bytes, alignment, ret);
        self.changed(bytes.len, 0);
    }
};
pub fn print(init: std.process.Init, value: anytype) !void {
    const bytes = try std.json.Stringify.valueAlloc(init.gpa, value, .{});
    defer init.gpa.free(bytes);
    var out = std.Io.File.stdout().writer(init.io, &.{});
    try out.interface.writeAll(bytes);
    try out.interface.writeByte('\n');
    try out.interface.flush();
}
