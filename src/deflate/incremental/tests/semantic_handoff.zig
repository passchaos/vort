const std = @import("std");
const core = @import("../../../core.zig");
const h = @import("dictionary_borrows/helpers.zig");
const fixtures = @import("rolling_semantic/fixtures.zig");
const Linear = @import("rolling_semantic/oracle.zig").Linear;
const allocator = std.testing.allocator;
const guard = 0xa5;

fn expectHandoff(decoder: anytype, output: []u8, expected: core.StepResult) !void {
    const before = decoder.diagnostics();
    const reservoir = decoder.bit_buffer;
    const bits = decoder.bit_count;
    try std.testing.expectEqualDeep(expected, try decoder.drainSemanticToCompact(output));
    const after = decoder.diagnostics();
    try std.testing.expectEqual(before.frame_input_read, after.frame_input_read);
    try std.testing.expectEqual(reservoir, decoder.bit_buffer);
    try std.testing.expectEqual(bits, decoder.bit_count);
    try std.testing.expectEqual(before.output_written + core.stream_count.fromLocal(expected.progress.output_written), after.output_written);
    try std.testing.expect(std.mem.allEqual(u8, output[expected.progress.output_written..], guard));
}

fn appendAfterHandoff(comptime Decoder: type, fixture: fixtures.Fixture) !void {
    // The private generation stops just before a 258-byte distance-one match.
    // Its output ends in "BCA"; injecting Z must change only that next match.
    const prefix_len = 32513;
    const match_end = prefix_len + 258;
    const body = fixture.encoded[0..fixture.body_len];
    var history: [Decoder.recommended_history_len]u8 = undefined;
    var workspace: Decoder.SemanticWorkspace = undefined;
    var decoder = try Decoder.initWithHistory(.{ .expected_output_len = fixture.payload.len }, &history);
    try decoder.attachSemanticWorkspace(&workspace);
    const output = try allocator.alloc(u8, fixture.payload.len);
    defer allocator.free(output);
    @memset(output, guard);

    const first = try decoder.step(body, output[0..7]);
    try std.testing.expectEqual(.need_output, first.status);
    try std.testing.expectEqual(@as(usize, 7), first.progress.output_written);
    try std.testing.expectEqualStrings("fast_dynamic_block", decoder.diagnostics().phase_name);
    const active = decoder.diagnostics();
    try std.testing.expectError(error.InvalidStreamState, decoder.appendDictionary("Z"));
    try std.testing.expectEqualDeep(active, decoder.diagnostics());

    try expectHandoff(&decoder, output[7..7], .{ .status = .need_output });
    try expectHandoff(&decoder, output[7..8], .{ .status = .need_output, .progress = .{ .output_written = 1 } });
    try expectHandoff(&decoder, output[8..265], .{ .status = .need_output, .progress = .{ .output_written = 257 } });
    try expectHandoff(&decoder, output[265..], .{ .status = .need_input, .progress = .{ .output_written = prefix_len - 265 } });
    try std.testing.expectEqualSlices(u8, fixture.payload[0..prefix_len], output[0..prefix_len]);
    try std.testing.expectEqualStrings("symbols", decoder.diagnostics().phase_name);
    try std.testing.expectEqual(@as(core.StreamCount, 1), decoder.semanticBlocksStarted());
    try std.testing.expectEqual(@as(core.StreamCount, 0), decoder.semanticBlocksCompleted());

    const compact = decoder.diagnostics();
    try expectHandoff(&decoder, output[prefix_len..], .{ .status = .need_input });
    try decoder.appendDictionary("Z");
    try std.testing.expectEqualDeep(compact, decoder.diagnostics());
    try h.drain(&decoder, body[first.progress.input_read..], output[prefix_len..]);
    try std.testing.expect(std.mem.allEqual(u8, output[prefix_len..match_end], 'Z'));
    try std.testing.expectEqualSlices(u8, fixture.payload[match_end..], output[match_end..]);
    try decoder.finish();
}

test "Deflate semantic handoff drains only generated bytes and lets a dictionary change the next match" {
    const fixture = try fixtures.capacityRegression(allocator);
    defer fixture.deinit(allocator);
    inline for (.{ h.Raw, Linear }) |Decoder| try appendAfterHandoff(Decoder, fixture);
}

fn handoffAtNonfinalEob(comptime Decoder: type, fixture: fixtures.Fixture, boundary: core.StepResult, position: h.deflate.BlockBoundaryPosition, output: []u8) !void {
    var history: [Decoder.recommended_history_len]u8 = undefined;
    var workspace: Decoder.SemanticWorkspace = undefined;
    var decoder = try Decoder.initWithHistory(.{ .expected_output_len = fixture.payload.len, .allow_trailing_data = true }, &history);
    try decoder.attachSemanticWorkspace(&workspace);
    @memset(output, guard);

    const prefix_len = boundary.progress.output_written;
    const before_drain = prefix_len - 5;
    const first = try decoder.step(fixture.encoded, output[0..before_drain]);
    try std.testing.expectEqual(.need_output, first.status);
    try std.testing.expectEqual(before_drain, first.progress.output_written);
    try std.testing.expectEqual(boundary.progress.input_read, first.progress.input_read);
    try std.testing.expectEqualStrings("fast_dynamic_block", decoder.diagnostics().phase_name);
    try std.testing.expectEqual(@as(?h.deflate.BlockBoundaryPosition, null), decoder.blockBoundaryPosition());

    try expectHandoff(&decoder, output[before_drain .. prefix_len - 1], .{ .status = .need_output, .progress = .{ .output_written = 4 } });
    try expectHandoff(&decoder, output[prefix_len - 1 ..], .{ .status = .need_input, .block_boundary = true, .progress = .{ .output_written = 1 } });
    try std.testing.expectEqual(@as(?h.deflate.BlockBoundaryPosition, position), decoder.blockBoundaryPosition());
    try std.testing.expectEqual(@as(core.StreamCount, 1), decoder.semanticBlocksCompleted());

    // The next block is unaligned and uses distance 32768: continuation must
    // retain both the original reservoir and the chronological history tail.
    try h.drain(&decoder, fixture.encoded[first.progress.input_read..fixture.body_len], output[prefix_len..]);
    try std.testing.expectEqualSlices(u8, fixture.payload, output);
    try decoder.finish();
}

test "Deflate semantic handoff reports nonfinal EOB and preserves the compact boundary position and history" {
    const fixture = try fixtures.transitions(allocator);
    defer fixture.deinit(allocator);
    const output = try allocator.alloc(u8, fixture.payload.len);
    defer allocator.free(output);
    var compact_history: [h.Raw.required_history_len]u8 = undefined;
    var compact = try h.Raw.initWithHistory(.{ .expected_output_len = fixture.payload.len }, &compact_history);
    const boundary = try compact.stepToBlockBoundary(fixture.encoded, output);
    try std.testing.expect(boundary.block_boundary);
    try std.testing.expectEqual(@as(usize, 32768 + 258 + 17), boundary.progress.output_written);
    const position = compact.blockBoundaryPosition() orelse return error.TestUnexpectedResult;
    try std.testing.expect(position.compressed_bit_offset != 0);
    try std.testing.expectEqualSlices(u8, fixture.payload[0..boundary.progress.output_written], output[0..boundary.progress.output_written]);
    inline for (.{ h.Raw, Linear }) |Decoder| try handoffAtNonfinalEob(Decoder, fixture, boundary, position, output);
}

fn handoffAtFinalEob(comptime Decoder: type, fixture: fixtures.Fixture, dictionary: []const u8, output: []u8) !void {
    var history: [Decoder.recommended_history_len]u8 = undefined;
    var workspace: Decoder.SemanticWorkspace = undefined;
    var decoder = try Decoder.initWithDictionary(.{ .allow_trailing_data = true, .expected_output_len = fixture.payload.len }, &history, dictionary);
    try decoder.attachSemanticWorkspace(&workspace);
    @memset(output, guard);

    const first = try decoder.step(fixture.encoded, &.{});
    try std.testing.expectEqual(.need_output, first.status);
    try std.testing.expectEqual(fixture.body_len, first.progress.input_read);
    try std.testing.expectEqualSlices(u8, &fixtures.suffix, fixture.encoded[first.progress.input_read..]);
    try std.testing.expectEqualStrings("fast_dynamic_block", decoder.diagnostics().phase_name);
    try expectHandoff(&decoder, output, .{ .status = .done, .progress = .{ .output_written = fixture.payload.len } });
    try std.testing.expectEqualSlices(u8, fixture.payload, output[0..fixture.payload.len]);
    try std.testing.expectEqual(@as(core.StreamCount, 1), decoder.semanticBlocksCompleted());
    const done = decoder.diagnostics();
    try expectHandoff(&decoder, output[fixture.payload.len..], .{ .status = .done });
    try std.testing.expectEqualDeep(done, decoder.diagnostics());
    try decoder.finish();
}

test "Deflate semantic handoff commits final EOB without consuming a suffix" {
    const dictionary = "seed";
    const fixture = try fixtures.dictionaryDynamic(allocator, dictionary);
    defer fixture.deinit(allocator);
    const output = try allocator.alloc(u8, fixture.payload.len + 3);
    defer allocator.free(output);
    inline for (.{ h.Raw, Linear }) |Decoder| try handoffAtFinalEob(Decoder, fixture, dictionary, output);
}

test "Deflate semantic handoff rejects active writer overlaps and a prematurely finished stream" {
    const fixture = try fixtures.capacityRegression(allocator);
    defer fixture.deinit(allocator);
    var history: [h.Raw.recommended_history_len]u8 = @splat(guard);
    var workspace: h.Raw.SemanticWorkspace = undefined;
    var decoder = try h.Raw.initWithHistory(.{}, &history);
    try decoder.attachSemanticWorkspace(&workspace);
    var output = [_]u8{guard};
    try expectHandoff(&decoder, &output, .{ .status = .need_input });
    _ = try decoder.step(fixture.encoded, &.{});
    const active = decoder.diagnostics();
    try std.testing.expectEqualStrings("fast_dynamic_block", active.phase_name);
    // The second half is outside the compact ring but is still an active writer.
    for ([_][]u8{ history[h.Raw.required_history_len..][0..1], std.mem.asBytes(&workspace)[0..1] }) |overlap| {
        try std.testing.expectError(error.InvalidBlockPlan, decoder.drainSemanticToCompact(overlap));
        try std.testing.expectEqualDeep(active, decoder.diagnostics());
    }
    try expectHandoff(&decoder, &output, .{ .status = .need_output, .progress = .{ .output_written = 1 } });
    try std.testing.expectEqual(fixture.payload[0], output[0]);
    try std.testing.expectError(error.TruncatedFrame, decoder.finish());
    const finished = decoder.diagnostics();
    output[0] = guard;
    try std.testing.expectError(error.InvalidStreamState, decoder.drainSemanticToCompact(&output));
    try std.testing.expectEqualDeep(finished, decoder.diagnostics());
    try std.testing.expectEqual(@as(u8, guard), output[0]);
}

test "Deflate semantic handoff can resume after an output limit plateau" {
    const dictionary = "seed";
    const fixture = try fixtures.dictionaryDynamic(allocator, dictionary);
    defer fixture.deinit(allocator);
    const output = try allocator.alloc(u8, fixture.payload.len);
    defer allocator.free(output);
    @memset(output, guard);
    var history: [h.Raw.recommended_history_len]u8 = undefined;
    var workspace: h.Raw.SemanticWorkspace = undefined;
    var decoder = try h.Raw.initWithDictionary(.{}, &history, dictionary);
    try decoder.attachSemanticWorkspace(&workspace);
    const first = try decoder.step(fixture.encoded[0..fixture.body_len], &.{});
    try std.testing.expectEqual(.need_output, first.status);
    decoder.options.stop_at_output_limit = true;
    decoder.options.max_output_len = 1;
    try expectHandoff(&decoder, output, .{ .status = .need_output, .progress = .{ .output_written = 1 } });
    try expectHandoff(&decoder, output[1..], .{ .status = .need_output });
    decoder.options.max_output_len = fixture.payload.len;
    try expectHandoff(&decoder, output[1..], .{ .status = .done, .progress = .{ .output_written = output.len - 1 } });
    try std.testing.expectEqualSlices(u8, fixture.payload, output);
    try decoder.finish();
}

test "Deflate semantic handoff checks expected size at final EOB and rejects retry on failure" {
    const dictionary = "seed";
    const fixture = try fixtures.dictionaryDynamic(allocator, dictionary);
    defer fixture.deinit(allocator);
    const output = try allocator.alloc(u8, fixture.payload.len);
    defer allocator.free(output);
    var history: [h.Raw.recommended_history_len]u8 = undefined;
    var workspace: h.Raw.SemanticWorkspace = undefined;
    var decoder = try h.Raw.initWithDictionary(.{ .expected_output_len = fixture.payload.len + 1 }, &history, dictionary);
    try decoder.attachSemanticWorkspace(&workspace);
    const first = try decoder.step(fixture.encoded[0..fixture.body_len], &.{});
    try std.testing.expectEqual(.need_output, first.status);
    try std.testing.expectError(error.SizeMismatch, decoder.drainSemanticToCompact(output));
    const failed = decoder.diagnostics();
    try std.testing.expectEqualStrings("SizeMismatch", failed.last_error_name);
    try std.testing.expectEqual(@as(core.StreamCount, fixture.payload.len), failed.output_written);
    try std.testing.expectEqualSlices(u8, fixture.payload, output);
    try std.testing.expectError(error.InvalidStreamState, decoder.drainSemanticToCompact(&.{}));
    try std.testing.expectEqualDeep(failed, decoder.diagnostics());
}
