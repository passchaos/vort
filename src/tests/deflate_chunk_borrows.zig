//! Package-root chunk consumers share the same first-write admission boundary.
const std = @import("std");

const Kind = enum { raw, zlib, gzip };

fn decode(comptime R: type, comptime kind: Kind, chunks: []const []const u8, scratch: []u8, output: []u8) !usize {
    return switch (kind) {
        .raw => (try R.decodeRawDeflateChunks(chunks, scratch, output)).output_written,
        .zlib => R.decodeZlibChunks(chunks, scratch, output),
        .gzip => R.decodeGzipChunks(chunks, scratch, output),
    };
}

pub fn contracts(comptime R: type) !void {
    const raw = [_]u8{ 1, 4, 0, 0xfb, 0xff, 'a', 'b', 'c', 'd' };
    // Independently generated by Python zlib 1.2.11, level 0, windows 15/31.
    const zlib = [_]u8{ 0x78, 1, 1, 4, 0, 0xfb, 0xff, 'a', 'b', 'c', 'd', 3, 0xd8, 1, 0x8b };
    const gzip = [_]u8{ 0x1f, 0x8b, 8, 0, 0, 0, 0, 0, 4, 3, 1, 4, 0, 0xfb, 0xff, 'a', 'b', 'c', 'd', 0x11, 0xcd, 0x82, 0xed, 4, 0, 0, 0 };
    inline for (.{ Kind.raw, Kind.zlib, Kind.gzip }) |kind| {
        const wire: []const u8 = switch (kind) {
            .raw => &raw,
            .zlib => &zlib,
            .gzip => &gzip,
        };
        const prefix: usize = switch (kind) {
            .raw => 5,
            .zlib => 7,
            .gzip => 15,
        };
        var backing: [64]u8 = @splat(0xa5);
        @memcpy(backing[0 .. wire.len - prefix], wire[prefix..]);
        const before = backing;
        const chunks = [_][]const u8{ wire[0..prefix], backing[0 .. wire.len - prefix] };
        var output: [4]u8 = @splat(0xb6);
        try std.testing.expectError(error.InvalidBlockPlan, decode(R, kind, &chunks, backing[0..wire.len], &output));
        try std.testing.expectEqualSlices(u8, &before, &backing);
        for (output) |byte| try std.testing.expectEqual(@as(u8, 0xb6), byte);

        var independent: [64]u8 = undefined;
        try std.testing.expectEqual(@as(usize, 4), try decode(R, kind, &chunks, &independent, &output));
        try std.testing.expectEqualSlices(u8, "abcd", &output);
        try std.testing.expectEqualSlices(u8, &before, &backing);

        // One real source remains borrowed even with aliased undersized scratch.
        const single = [_][]const u8{ "", wire, "" };
        try std.testing.expectEqual(@as(usize, 4), try decode(R, kind, &single, &output, &output));
        try std.testing.expectEqualSlices(u8, "abcd", &output);
    }
}
