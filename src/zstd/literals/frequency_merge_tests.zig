//! Independent frequency merge checks. The oracle accumulates each symbol in
//! u64 and counts support separately; this helper never imports its caller.
const std = @import("std");

fn oracle(rows: *const [4][256]u32, output: *[256]u32) !usize {
    var active: usize = 0;
    for (output, 0..) |*frequency, symbol| {
        var sum: u64 = 0;
        for (rows) |row| sum += row[symbol];
        try std.testing.expect(sum <= 131072);
        frequency.* = @intCast(sum);
        active += @intFromBool(sum != 0);
    }
    return active;
}

fn compare(comptime Module: type, rows: *const [4][256]u32) !void {
    const before = rows.*;
    var expected: [256]u32 = undefined;
    const expected_active = try oracle(rows, &expected);
    var scalar: [256]u32 = @splat(0xa5a5_a5a5);
    var guarded: [258]u32 = @splat(0xa5a5_a5a5);
    const actual: *[256]u32 = guarded[1..257];
    try std.testing.expectEqual(expected_active, Module.scalarReference(rows, &scalar));
    try std.testing.expectEqual(expected_active, Module.mergeActive(rows, actual));
    try std.testing.expectEqualSlices(u32, &expected, &scalar);
    try std.testing.expectEqualSlices(u32, &expected, actual);
    try std.testing.expectEqual(@as(u32, 0xa5a5_a5a5), guarded[0]);
    try std.testing.expectEqual(@as(u32, 0xa5a5_a5a5), guarded[257]);
    try std.testing.expectEqualDeep(before, rows.*);
}

pub fn contracts(comptime Module: type) !void {
    var rows: [4][256]u32 = @splat(@splat(0));
    try compare(Module, &rows);
    // Every stream contributes to the same symbol, including the maximum
    // legal total. Zero symbols must overwrite caller poison as well.
    for ([_]usize{ 0, 1, 127, 128, 254, 255 }) |symbol| {
        rows = @splat(@splat(0));
        for (&rows) |*row| row[symbol] = 32768;
        try compare(Module, &rows);
        rows = @splat(@splat(0));
        rows[3][symbol] = 131072;
        try compare(Module, &rows);
    }
    // Disjoint row supports and overlapping supports throughout the alphabet.
    rows = @splat(@splat(0));
    for (0..256) |symbol| rows[symbol % 4][symbol] = @intCast(1 + symbol);
    try compare(Module, &rows);
    for (&rows, 0..) |*row, stream| {
        for (row, 0..) |*frequency, symbol| frequency.* = @intCast(1 + (symbol * 17 + stream * 31) % 97);
    }
    try compare(Module, &rows);
    for (&rows, 0..) |*row, stream| {
        for (row, 0..) |*frequency, symbol| frequency.* = if ((symbol + stream) % 11 == 0) @intCast(1 + symbol * 3) else 0;
    }
    try compare(Module, &rows);

    // Build legal frequency partitions from real generated bytes, with each
    // stream receiving one contiguous quarter and independent source counting.
    var random: u32 = 0x6a09e667;
    var bytes: [131072]u8 = undefined;
    for ([_]usize{ 0, 1, 63, 64, 1023, 1024, 65535, 65536, 65537, bytes.len }) |length| {
        rows = @splat(@splat(0));
        for (bytes[0..length], 0..) |*byte, index| {
            random = random *% 1664525 +% 1013904223;
            byte.* = if (index % 7 == 0) 255 else @truncate(random >> 24);
        }
        const quarter = length / 4 + @intFromBool(length % 4 != 0);
        for (bytes[0..length], 0..) |byte, index| rows[@min(index / @max(1, quarter), 3)][byte] += 1;
        try compare(Module, &rows);
        var actual: [256]u32 = undefined;
        _ = Module.mergeActive(&rows, &actual);
        var expected: [256]u32 = @splat(0);
        for (bytes[0..length]) |byte| expected[byte] += 1;
        try std.testing.expectEqualSlices(u32, &expected, &actual);
    }

    // Each pointer satisfies u32 alignment but is deliberately offset from
    // SIMD alignment. Guards protect both ends of input and output ownership.
    var input_storage: [1026]u32 align(32) = @splat(0xdead_beef);
    const unaligned_rows: *[4][256]u32 = @ptrCast(input_storage[1..1025].ptr);
    try std.testing.expectEqual(@as(usize, 4), @intFromPtr(unaligned_rows) % 32);
    for (unaligned_rows, 0..) |*row, stream| {
        for (row, 0..) |*frequency, symbol| frequency.* = @intCast((symbol + stream * 13) % 31);
    }
    const unchanged = input_storage;
    var output_storage: [258]u32 align(32) = @splat(0xa5a5_a5a5);
    const unaligned_output: *[256]u32 = output_storage[1..257];
    try std.testing.expectEqual(@as(usize, 4), @intFromPtr(unaligned_output) % 32);
    var expected: [256]u32 = undefined;
    const expected_active = try oracle(unaligned_rows, &expected);
    try std.testing.expectEqual(expected_active, Module.mergeActive(unaligned_rows, unaligned_output));
    try std.testing.expectEqualSlices(u32, &expected, unaligned_output);
    try std.testing.expectEqualDeep(unchanged, input_storage);
    try std.testing.expectEqual(@as(u32, 0xa5a5_a5a5), output_storage[0]);
    try std.testing.expectEqual(@as(u32, 0xa5a5_a5a5), output_storage[257]);
}

pub fn histograms(comptime Hist: type) !void {
    var block: [131072]u8 = undefined;
    var random: u32 = 0x243f6a88;
    for (&block, 0..) |*byte, index| {
        random = random *% 1664525 +% 1013904223;
        byte.* = if (index % 17 == 0) 255 else @truncate(random >> 24);
    }
    var histogram = try Hist.init(&block);
    for ([_]usize{ 0, 1, 63, 64, 1023, 1024, 1025, 16383, 16384, 65535, 65536, 65537, block.len, 1023, 0 }) |length| {
        for ([_]usize{ 0, length / 2, length }) |prefix| {
            const tail = block.len - (length - prefix);
            try histogram.update(prefix, tail);
            var expected: [256]u32 = @splat(0);
            for (block[0..prefix]) |byte| expected[byte] += 1;
            for (block[tail..]) |byte| expected[byte] += 1;
            var expected_active: usize = 0;
            for (expected) |frequency| expected_active += @intFromBool(frequency != 0);
            const unchanged = histogram;
            var guarded: [258]u32 = @splat(0xa5a5_a5a5);
            const actual: *[256]u32 = guarded[1..257];
            try std.testing.expectEqual(expected_active, histogram.totalFrequenciesAndCount(actual));
            try std.testing.expectEqualSlices(u32, &expected, actual);
            var scalar: [256]u32 = undefined;
            histogram.totalFrequencies(&scalar);
            try std.testing.expectEqualSlices(u32, &scalar, actual);
            try std.testing.expectEqualDeep(unchanged, histogram);
            try std.testing.expectEqual(@as(u32, 0xa5a5_a5a5), guarded[0]);
            try std.testing.expectEqual(@as(u32, 0xa5a5_a5a5), guarded[257]);
        }
    }
    @memset(&block, 0xff);
    histogram = try Hist.init(&block);
    try histogram.update(block.len, block.len);
    var expected: [256]u32 = @splat(0);
    expected[255] = 131072;
    var actual: [256]u32 = undefined;
    try std.testing.expectEqual(@as(usize, 1), histogram.totalFrequenciesAndCount(&actual));
    try std.testing.expectEqualSlices(u32, &expected, &actual);
}
